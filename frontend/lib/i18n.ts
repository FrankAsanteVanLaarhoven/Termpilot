export const REQUIRED_KEYS = Object.keys(EN);

function overlay(base: Record<string, string>, extra: Record<string, string>): Record<string, string> {
  return { ...base, ...extra };
}

export const MESSAGES: Record<Locale, Record<string, string>> = Object.fromEntries(
  LOCALES.map((code) => [code, code === "en" ? EN : overlay(EN, COMPLETE[code] ?? {})]),
) as Record<Locale, Record<string, string>>;

export function t(locale: Locale, key: string): string {
  return MESSAGES[locale]?.[key] ?? MESSAGES.en[key] ?? key;
}

export function isFallback(locale: Locale, key: string): boolean {
  if (locale === "en") return false;
  return !MESSAGES[locale]?.[key] && Boolean(MESSAGES.en[key]);
}

export function isLocale(value: string): value is Locale {
  return (LOCALES as readonly string[]).includes(value);
}
